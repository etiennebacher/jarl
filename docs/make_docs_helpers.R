.extract_documentation <- function(rs_file, .ref = NULL) {
  rust_script <- readLines(rs_file)

  doc_markers <- list(
    start = grep("^/// <!-- docs: start -->", rust_script),
    end = grep("^/// <!-- docs: end -->", rust_script)
  )

  if (identical(lengths(doc_markers), c(start = 0L, end = 0L))) {
    return(NULL)
  } else if (!identical(lengths(doc_markers), c(start = 1L, end = 1L))) {
    if (is.null(.ref)) {
      .ref <- rs_file
    }
    stop("Documentation markers in `", .ref, "` are malformed.")
  }

  gsub(
    "^///\\s?",
    "",
    rust_script[(doc_markers$start + 1):(doc_markers$end - 1)]
  )
}

create_rule_md <- function(rule, lints_dir) {
  rule_name <- basename(rule)
  rs_file <- file.path(lints_dir, rule, paste0(rule_name, ".rs"))
  options_rs <- file.path(lints_dir, rule, "options.rs")

  if (!file.exists(rs_file)) {
    stop(
      c(
        "Cannot find rust script for rule `",
        rule_name,
        "`\nExpected: ",
        rs_file
      )
    )
  }

  doc_content <- .extract_documentation(rs_file, rule_name)

  if (is.null(doc_content)) {
    return(FALSE)
  }

  # inspect version metadata
  version_loc <- grep("^Version added:", doc_content)

  if (length(version_loc) == 0) {
    stop("No 'version added' meta in rule `", rule_name, "`.")
  } else if (length(version_loc) != 1) {
    stop("Multiple 'version added' meta in rule `", rule_name, "`.")
  } else if (version_loc != 1) {
    stop(
      "The 'version added' meta in rule `",
      rule_name,
      "` is not the first line of the documentation."
    )
  }

  version_added <- gsub(
    ".*(\\d+\\.\\d+\\.\\d+).*",
    "\\1",
    doc_content[version_loc]
  )

  if (!grepl("^\\d+\\.\\d+\\.\\d+$", version_added)) {
    stop("The 'version added' meta for rule `", rule_name, "` is malformed.")
  }

  exref_loc <- grep("^## (Example|Reference)s?", doc_content)

  if (length(exref_loc) == 0) {
    main_content <- doc_content[2:length(doc_content)]
    exref_content <- NULL
  } else {
    exref_loc <- min(exref_loc)
    main_content <- doc_content[2:(exref_loc - 1)]
    exref_content <- doc_content[exref_loc:length(doc_content)]
  }

  if (file.exists(options_rs)) {
    options_content <- .extract_documentation(
      options_rs,
      file.path(rule_name, "options.rs")
    )

    options_content <- c(
      "## Configuration options\n",
      paste0(
        "The operation of the `",
        rule_name,
        "` rule can be customised in the ",
        "[configuration file](../reference/config-file.md).\n"
      ),
      options_content,
      ""
    )

    if (main_content[length(main_content)] != "") {
      options_content <- c("", options_content)
    }
  } else {
    options_content <- NULL
  }

  # make documentation output
  rule_doc <- list(
    title = paste0("# ", rule_name, "\n"),
    version_tag = paste0(
      "!!! note low-opacity \"Added in ",
      version_added,
      "\"\n"
    ),
    main_content = main_content,
    options_content = options_content,
    exref_content = exref_content
  )

  writeLines(unlist(rule_doc), paste0("docs/rules/", rule_name, ".md"))

  return(TRUE)
}

create_index_md <- function(readme = "README.md", out = "docs/index.md") {
  content <- readLines(readme, warn = FALSE)
  content <- gsub(
    "align=\"center\"",
    "style=\"text-align: center !important\"",
    content
  )
  content <- content[-grep("<h1>jarl</h1>", content, fixed = TRUE)]

  content <- c(
    "---",
    "title: Jarl",
    "---",
    "",
    "<!-- ============ -->",
    "<!-- THIS FILE IS AUTOMATICALLY GENERATED. -->",
    "<!-- MODIFY THE README INSTEAD. -->",
    "<!-- ============ -->",
    "",
    content
  )
  writeLines(content, con = out)
}

# Replace the list of rule pages in the navigation of `zensical.toml`, between
# the markers `# <rules-nav:start>` and `# <rules-nav:end>`.
update_rules_nav <- function(rule_pages, config = "docs/zensical.toml") {
  lines <- readLines(config, warn = FALSE)
  start <- grep("# <rules-nav:start>", lines, fixed = TRUE)
  end <- grep("# <rules-nav:end>", lines, fixed = TRUE)
  if (length(start) != 1 || length(end) != 1 || start >= end) {
    stop("Cannot find the rules navigation markers in `", config, "`.")
  }

  indent <- sub("#.*", "", lines[start])
  new_lines <- c(
    lines[seq_len(start)],
    paste0(
      indent,
      "{ \"",
      sub("\\.md$", "", basename(rule_pages)),
      "\" = \"",
      rule_pages,
      "\" },"
    ),
    lines[end:length(lines)]
  )
  writeLines(new_lines, config)
}

create_config_md <- function(
  lints_dir,
  config_base = "docs/reference/_config-file.md",
  config_out = "docs/reference/config-file.md"
) {
  config_content <- readLines(config_base)

  options_files <- list.files(
    lints_dir,
    pattern = "options\\.rs$",
    recursive = TRUE
  )

  options_rules <- basename(dirname(options_files))

  config_rules <- c(
    "## Rule-specific arguments",
    "",
    "The operation of some rules can be customised with arguments in the",
    "configuration file, see the relevant rule documentation page for details:",
    "",
    paste0(
      "* ",
      paste0(
        "[`",
        options_rules,
        "`](../rules/",
        options_rules,
        ".md#configuration-options)"
      )
    )
  )

  header_content <- c(
    "<!-- ============ -->",
    "<!-- THIS FILE IS AUTOMATICALLY GENERATED. -->",
    "<!-- MODIFY THE DOCS/REFERENCE/_CONFIG-FILE.MD INSTEAD. -->",
    "<!-- ============ -->"
  )

  new_config_content <- c(header_content, "", config_content, "", config_rules)

  writeLines(new_config_content, config_out)
}
